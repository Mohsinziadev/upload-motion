function makeWav(): File {
  const rate = 22050;
  const seconds = 3;
  const samples = rate * seconds;
  const buffer = new ArrayBuffer(44 + samples * 2);
  const view = new DataView(buffer);
  const write = (offset: number, value: string) => [...value].forEach((char, i) => view.setUint8(offset + i, char.charCodeAt(0)));
  write(0, 'RIFF');
  view.setUint32(4, 36 + samples * 2, true);
  write(8, 'WAVE');
  write(12, 'fmt ');
  view.setUint32(16, 16, true);
  view.setUint16(20, 1, true);
  view.setUint16(22, 1, true);
  view.setUint32(24, rate, true);
  view.setUint32(28, rate * 2, true);
  view.setUint16(32, 2, true);
  view.setUint16(34, 16, true);
  write(36, 'data');
  view.setUint32(40, samples * 2, true);
  const notes = [261.63, 329.63, 392, 523.25, 392, 329.63];
  for (let i = 0; i < samples; i += 1) {
    const t = i / rate;
    const beat = Math.floor(t * 4) % notes.length;
    const local = (t * 4) % 1;
    const envelope = (0.35 + 0.65 * Math.exp(-local * 1.6)) * (0.55 + 0.45 * Math.sin((t * Math.PI) / seconds));
    const value = Math.sin(2 * Math.PI * notes[beat]! * t) * 0.6 + Math.sin(2 * Math.PI * notes[beat]! * 2 * t) * 0.2;
    view.setInt16(44 + i * 2, Math.max(-1, Math.min(1, value * envelope)) * 0x7fff, true);
  }
  return new File([buffer], 'arpeggio.wav', { type: 'audio/wav' });
}

async function makeVideo(): Promise<File | null> {
  if (typeof MediaRecorder === 'undefined') return null;
  const canvas = document.createElement('canvas');
  canvas.width = 320;
  canvas.height = 180;
  const ctx = canvas.getContext('2d')!;
  const stream = canvas.captureStream(30);
  const type = ['video/webm;codecs=vp9', 'video/webm;codecs=vp8', 'video/webm', 'video/mp4'].find((t) => MediaRecorder.isTypeSupported(t));
  if (!type) return null;
  const recorder = new MediaRecorder(stream, { mimeType: type, videoBitsPerSecond: 900_000 });
  const chunks: Blob[] = [];
  recorder.ondataavailable = (event) => event.data.size > 0 && chunks.push(event.data);
  const done = new Promise<void>((resolve) => (recorder.onstop = () => resolve()));
  recorder.start(100);
  const start = performance.now();
  await new Promise<void>((resolve) => {
    const draw = (now: number) => {
      const t = (now - start) / 1000;
      const hue = (t * 120) % 360;
      const gradient = ctx.createLinearGradient(0, 0, 320, 180);
      gradient.addColorStop(0, `hsl(${hue} 80% 55%)`);
      gradient.addColorStop(1, `hsl(${(hue + 90) % 360} 80% 45%)`);
      ctx.fillStyle = gradient;
      ctx.fillRect(0, 0, 320, 180);
      ctx.fillStyle = 'rgba(255,255,255,0.9)';
      ctx.beginPath();
      ctx.arc(40 + ((t * 160) % 240), 90 + Math.sin(t * 6) * 40, 22, 0, Math.PI * 2);
      ctx.fill();
      ctx.font = '700 22px system-ui, sans-serif';
      ctx.fillText(`${t.toFixed(1)}s`, 250, 160);
      if (t < 1.8) requestAnimationFrame(draw);
      else resolve();
    };
    requestAnimationFrame(draw);
  });
  recorder.stop();
  await done;
  stream.getTracks().forEach((track) => track.stop());
  const blob = new Blob(chunks, { type: type.split(';')[0] });
  return new File([blob], type.includes('mp4') ? 'motion-clip.mp4' : 'motion-clip.webm', { type: blob.type });
}

const CRC_TABLE = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k += 1) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
function crc32(bytes: Uint8Array) {
  let crc = 0xffffffff;
  for (const byte of bytes) crc = CRC_TABLE[(crc ^ byte) & 0xff]! ^ (crc >>> 8);
  return (crc ^ 0xffffffff) >>> 0;
}

/** A valid ZIP (stored, no compression) containing two text files. */
function makeZip(): File {
  const encoder = new TextEncoder();
  const entries = [
    { name: 'README.md', data: encoder.encode('# Sample archive\nCreated in your browser by the upload-motion playground.\n') },
    { name: 'data/notes.txt', data: encoder.encode('Archives get the pixel-assembly treatment in the adaptive preset.\n'.repeat(40)) },
  ];
  const parts: Uint8Array[] = [];
  const central: Uint8Array[] = [];
  let offset = 0;
  for (const entry of entries) {
    const name = encoder.encode(entry.name);
    const crc = crc32(entry.data);
    const local = new DataView(new ArrayBuffer(30));
    local.setUint32(0, 0x04034b50, true);
    local.setUint16(4, 20, true);
    local.setUint32(14, crc, true);
    local.setUint32(18, entry.data.length, true);
    local.setUint32(22, entry.data.length, true);
    local.setUint16(26, name.length, true);
    parts.push(new Uint8Array(local.buffer), name, entry.data);
    const header = new DataView(new ArrayBuffer(46));
    header.setUint32(0, 0x02014b50, true);
    header.setUint16(4, 20, true);
    header.setUint16(6, 20, true);
    header.setUint32(16, crc, true);
    header.setUint32(20, entry.data.length, true);
    header.setUint32(24, entry.data.length, true);
    header.setUint16(28, name.length, true);
    header.setUint32(42, offset, true);
    central.push(new Uint8Array(header.buffer), name);
    offset += 30 + name.length + entry.data.length;
  }
  const centralSize = central.reduce((sum, part) => sum + part.length, 0);
  const end = new DataView(new ArrayBuffer(22));
  end.setUint32(0, 0x06054b50, true);
  end.setUint16(8, entries.length, true);
  end.setUint16(10, entries.length, true);
  end.setUint32(12, centralSize, true);
  end.setUint32(16, offset, true);
  return new File([...parts, ...central, new Uint8Array(end.buffer)] as BlobPart[], 'assets.zip', { type: 'application/zip' });
}

export async function createSampleFile(kind: SampleKind): Promise<File | null> {
  switch (kind) {
    case 'image':
      return makeImage();
    case 'pdf':
      return makePdf();
    case 'csv':
      return makeCsv();
    case 'json':
      return makeJson();
    case 'code':
      return makeCode();
    case 'audio':
      return makeWav();
    case 'video':
      return makeVideo();
    case 'zip':
      return makeZip();
    case 'text':
      return makeText();
  }
}

export async function createSampleSet(kinds: readonly SampleKind[]): Promise<File[]> {
  const files = await Promise.all(kinds.map((kind) => createSampleFile(kind)));
  return files.filter((file): file is File => file !== null);
}

/** A file larger than `limit`, for demonstrating validation. Backed by a single zero-filled buffer. */
export function createOversizedFile(limit: number): File {
  return new File([new Uint8Array(limit + 1024 * 1024)], 'raw-footage.mov', { type: 'video/quicktime' });
}

