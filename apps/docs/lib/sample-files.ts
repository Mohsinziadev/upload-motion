'use client';

/**
 * Generates real sample files in the browser so visitors can try every preset
 * without hunting for files. Nothing is fetched from a server.
 */

export type SampleKind = 'image' | 'pdf' | 'csv' | 'json' | 'code' | 'audio' | 'video' | 'zip' | 'text';

export const SAMPLE_LABELS: Record<SampleKind, string> = {
  image: 'Image (PNG)',
  pdf: 'PDF',
  csv: 'Spreadsheet (CSV)',
  json: 'JSON',
  code: 'Code (TS)',
  audio: 'Audio (WAV)',
  video: 'Video (WebM)',
  zip: 'Archive (ZIP)',
  text: 'Notes (TXT)',
};

let imageCounter = 0;

async function makeImage(): Promise<File> {
  imageCounter += 1;
  const index = imageCounter;
  const canvas = document.createElement('canvas');
  canvas.width = 640;
  canvas.height = 440;
  const ctx = canvas.getContext('2d')!;
  const palettes = [
    ['#5b5ef4', '#a855f7', '#f472b6'],
    ['#0ea5e9', '#22d3ee', '#a3e635'],
    ['#f97316', '#f43f5e', '#8b5cf6'],
    ['#14b8a6', '#6366f1', '#fde047'],
  ];
  const [a, b, c] = palettes[index % palettes.length]!;
  const gradient = ctx.createLinearGradient(0, 0, 640, 440);
  gradient.addColorStop(0, a!);
  gradient.addColorStop(0.55, b!);
  gradient.addColorStop(1, c!);
  ctx.fillStyle = gradient;
  ctx.fillRect(0, 0, 640, 440);
  for (let i = 0; i < 14; i += 1) {
    ctx.beginPath();
    ctx.fillStyle = `rgba(255,255,255,${0.06 + (i % 5) * 0.04})`;
    ctx.arc(((i * 137) % 640) + 20, ((i * 89) % 440) + 10, 30 + ((i * 53) % 110), 0, Math.PI * 2);
    ctx.fill();
  }
  ctx.strokeStyle = 'rgba(255,255,255,0.85)';
  ctx.lineWidth = 6;
  ctx.beginPath();
  for (let x = 0; x <= 640; x += 4) ctx.lineTo(x, 330 + Math.sin((x + index * 40) / 38) * 22);
  ctx.stroke();
  ctx.fillStyle = '#fff';
  ctx.font = '700 44px system-ui, sans-serif';
  ctx.fillText('upload-motion', 40, 96);
  const blob = await new Promise<Blob>((resolve) => canvas.toBlob((value) => resolve(value!), 'image/png'));
  const names = ['aurora', 'sunset', 'lagoon', 'citrus'];
  return new File([blob], `${names[index % names.length]}-${index}.png`, { type: 'image/png' });
}

function makePdf(): File {
  const text = 'Quarterly report – generated by the upload-motion playground';
  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>',
    null,
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
  ];
  const stream = `BT /F1 20 Tf 60 760 Td (${text.replace(/[()\\]/g, '')}) Tj ET`;
  objects[3] = `<< /Length ${stream.length} >>\nstream\n${stream}\nendstream`;
  let body = '%PDF-1.4\n';
  const offsets: number[] = [];
  objects.forEach((object, index) => {
    offsets.push(body.length);
    body += `${index + 1} 0 obj\n${object}\nendobj\n`;
  });
  const xref = body.length;
  body += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (const offset of offsets) body += `${String(offset).padStart(10, '0')} 00000 n \n`;
  body += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return new File([body], 'quarterly-report.pdf', { type: 'application/pdf' });
}

function makeCsv(): File {
  const rows = ['month,region,orders,revenue'];
  const regions = ['EMEA', 'APAC', 'AMER'];
  for (let i = 0; i < 360; i += 1) {
    rows.push(`2026-${String((i % 12) + 1).padStart(2, '0')},${regions[i % 3]},${120 + ((i * 37) % 400)},${(4200 + ((i * 911) % 9000)).toFixed(2)}`);
  }
  return new File([rows.join('\n')], 'sales-2026.csv', { type: 'text/csv' });
}

